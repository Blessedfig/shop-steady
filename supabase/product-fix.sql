-- Product fixer for Downtown Stube: keeps Shopify product data clean, Faire items first.
-- Run after shopify.sql: Supabase > SQL Editor > New query > paste > Run. Running it again is safe.
-- Then deploy the Edge Function "product-fix" (supabase/functions/product-fix) with "Verify JWT" OFF, like shopify-sync.
--
-- How it fits together:
--   faire_order_lines   : lines from Faire order exports (Faire has no API for stores, so the owner or a manager uploads
--                         the CSV from Faire > Orders). Gives the real cost per item, units per case and suggested retail.
--   product_lookups     : ISBNs found by title and author (Google Books, Open Library) for books with no barcode.
--   product_fixes       : what the fixer found. Every hour it rereads every product and proposes fixes (barcode, cost per
--                         item, retail price, product type, stock tracking) or flags something for a person.
--   product_fix_rules   : per rule, whether the owner lets it fix things on its own. All off until the owner turns one on.
-- Nothing reaches Shopify until the owner approves a fix (or turned on its rule). Approving puts the change in
-- shopify_changes, and the shopify-sync function sends it, exactly like a cost change proposed by hand.

-- product tags come in with the hourly product export (Faire's app tags its products "Faire")
alter table public.shopify_variants add column if not exists tags text;

-- more kinds of change can go to Shopify; changes made by an automatic rule say which rule
alter table public.shopify_changes drop constraint if exists shopify_changes_kind_check;
alter table public.shopify_changes add constraint shopify_changes_kind_check check (kind in ('cost','vendor','stock','barcode','price','type','tracked'));
alter table public.shopify_changes add column if not exists auto_rule text;
alter table public.shopify_changes add column if not exists fix_id bigint;
drop policy if exists "managers propose changes" on public.shopify_changes;
create policy "managers propose changes" on public.shopify_changes for insert to authenticated
  with check (public.role_rank(public.my_role()) >= 3 and status = 'pending' and applied_at is null and auto_rule is null and fix_id is null
              and kind in ('cost','vendor'));
-- people in the app may only write these columns: they propose (kind, item, values, note) and drop (status).
-- auto_rule and fix_id are set only by the server, so nobody can make their own change look approved.
revoke insert, update on public.shopify_changes from authenticated;
grant insert (kind, variant_id, old_value, new_value, note) on public.shopify_changes to authenticated;
grant update (status) on public.shopify_changes to authenticated;

create table if not exists public.faire_order_lines (
  line_key    text primary key,          -- order + product + option + sku, so a second upload of the same file adds nothing
  order_no    text,
  day         date,
  brand       text,
  product     text not null,
  option      text,
  sku         text,
  barcode     text,
  units       numeric,                   -- items received (cases x case size)
  unit_cost   numeric,                   -- what one item cost
  line_total  numeric,
  msrp        numeric,                   -- the brand's suggested retail for one item
  file        text,
  imported_by text not null default lower(coalesce(auth.jwt() ->> 'email','')),
  imported_at timestamptz not null default now()
);
create index if not exists faire_order_lines_sku on public.faire_order_lines (lower(sku));

create table if not exists public.product_lookups (
  variant_id bigint primary key,
  tried_at   timestamptz not null default now(),
  query      text,
  found      jsonb not null default '[]'::jsonb,  -- [{isbn, title, authors, publisher, year, source, link}]
  note       text
);

create table if not exists public.product_fixes (
  id          bigint generated by default as identity primary key,
  variant_id  bigint not null,
  product_id  bigint,
  title       text,
  kind        text not null check (kind in ('barcode','cost','price','type','tracked','check')),
  rule        text not null,
  old_value   text,
  new_value   text,
  confidence  text not null check (confidence in ('high','medium','low')),
  reason      text,
  evidence    jsonb not null default '{}'::jsonb,
  status      text not null default 'open' check (status in ('open','approved','applied','failed','dismissed')),
  change_id   bigint,
  error       text,
  found_at    timestamptz not null default now(),
  seen_at     timestamptz not null default now(),
  decided_by  text,
  decided_at  timestamptz,
  unique nulls not distinct (variant_id, rule, new_value)
);
create index if not exists product_fixes_status on public.product_fixes (status, kind);

create table if not exists public.product_fix_rules (
  rule   text primary key,
  auto   boolean not null default false,
  set_by text,
  set_at timestamptz
);

alter table public.faire_order_lines enable row level security;
alter table public.product_lookups enable row level security;
alter table public.product_fixes enable row level security;
alter table public.product_fix_rules enable row level security;

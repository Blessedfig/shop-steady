drop policy if exists "managers read fix rules" on public.product_fix_rules;
create policy "managers read fix rules" on public.product_fix_rules for select to authenticated using (public.role_rank(public.my_role()) >= 3);

-- Upload a Faire order export (rows already read and mapped in the app). Manager or owner.
create or replace function public.import_faire_rows(p_file text, p_rows jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare r jsonb; added int := 0; seen int := 0; k text;
begin
  if public.role_rank(public.my_role()) < 3 then raise exception 'Managers and the owner only'; end if;
  if jsonb_typeof(p_rows) <> 'array' or jsonb_array_length(p_rows) > 5000 then raise exception 'Send up to 5000 rows at a time'; end if;
  for r in select * from jsonb_array_elements(p_rows) loop
    if coalesce(trim(r->>'product'),'') = '' then continue; end if;
    seen := seen + 1;
    k := md5(concat_ws('|', lower(trim(r->>'order_no')), lower(trim(r->>'product')), lower(trim(r->>'option')), lower(trim(r->>'sku')), r->>'day'));
    insert into public.faire_order_lines (line_key, order_no, day, brand, product, option, sku, barcode, units, unit_cost, line_total, msrp, file)
    values (k, left(r->>'order_no',60), nullif(r->>'day','')::date, left(r->>'brand',200), left(r->>'product',300), left(r->>'option',200),
            left(r->>'sku',100), left(r->>'barcode',40), nullif(r->>'units','')::numeric, nullif(r->>'unit_cost','')::numeric,
            nullif(r->>'line_total','')::numeric, nullif(r->>'msrp','')::numeric, left(p_file,200))
    on conflict (line_key) do nothing;
    if found then added := added + 1; end if;
  end loop;
  return jsonb_build_object('rows', seen, 'added', added);
end $$;
revoke all on function public.import_faire_rows(text, jsonb) from public, anon;
grant execute on function public.import_faire_rows(text, jsonb) to authenticated;

-- Dismiss fixes (manager or owner). A dismissed fix does not come back unless the product changes again.
create or replace function public.dismiss_fixes(p_ids bigint[]) returns int
language plpgsql security definer set search_path = public as $$
declare n int;
begin
  if public.role_rank(public.my_role()) < 3 then raise exception 'Managers and the owner only'; end if;
  update public.product_fixes set status = 'dismissed', decided_by = lower(auth.jwt() ->> 'email'), decided_at = now()
   where id = any(p_ids) and status = 'open';
  get diagnostics n = row_count; return n;
end $$;
revoke all on function public.dismiss_fixes(bigint[]) from public, anon;
grant execute on function public.dismiss_fixes(bigint[]) to authenticated;

-- Approve fixes (owner only). p_picks: {"<fix id>": "<isbn>"} for a book where the owner picked the edition.
-- Puts each one in shopify_changes and returns their ids; the app then asks shopify-sync to send them.
create or replace function public.approve_fixes(p_ids bigint[], p_picks jsonb default '{}'::jsonb) returns bigint[]
language plpgsql security definer set search_path = public as $$
declare f public.product_fixes; v text; cid bigint; out bigint[] := '{}'; who text := lower(auth.jwt() ->> 'email');
begin
  if public.my_role() is distinct from 'owner' then raise exception 'Only the owner sends changes to Shopify'; end if;
  for f in select * from public.product_fixes where id = any(p_ids) and status in ('open','failed') and kind <> 'check' order by id limit 500 loop
    v := coalesce(f.new_value, p_picks ->> f.id::text);
    if v is null then continue; end if;
    if f.new_value is null and not exists (select 1 from jsonb_array_elements(f.evidence -> 'choices') c where c ->> 'isbn' = v) then continue; end if;
    insert into public.shopify_changes (kind, variant_id, old_value, new_value, note, fix_id, created_by)
      values (f.kind, f.variant_id, f.old_value, v, left(f.title, 200) || ' · ' || f.rule, f.id, who) returning id into cid;
    update public.product_fixes set status = 'approved', new_value = v, change_id = cid, decided_by = who, decided_at = now(), error = null where id = f.id;
    out := out || cid;
  end loop;
  return out;
end $$;
revoke all on function public.approve_fixes(bigint[], jsonb) from public, anon;
grant execute on function public.approve_fixes(bigint[], jsonb) to authenticated;

-- Undo an applied fix (owner): queues the old value back. The app sends it like any other change.
create or replace function public.undo_fix(p_id bigint) returns bigint
language plpgsql security definer set search_path = public as $$
declare f public.product_fixes; cid bigint;
begin
  if public.my_role() is distinct from 'owner' then raise exception 'Only the owner sends changes to Shopify'; end if;
  select * into f from public.product_fixes where id = p_id and status = 'applied';
  if f.id is null then raise exception 'Only an applied fix can be undone'; end if;
  if coalesce(f.old_value,'') = '' and f.kind in ('cost','price') then raise exception 'There was no earlier value to put back'; end if;
  insert into public.shopify_changes (kind, variant_id, old_value, new_value, note, created_by)
    values (f.kind, f.variant_id, f.new_value, coalesce(f.old_value,''), 'Undo: ' || left(f.title, 200), lower(auth.jwt() ->> 'email')) returning id into cid;
  update public.product_fixes set status = 'dismissed', error = 'Undone' where id = f.id;
  return cid;
end $$;
revoke all on function public.undo_fix(bigint) from public, anon;
grant execute on function public.undo_fix(bigint) to authenticated;

-- Turn a rule's automatic fixing on or off (owner). Automatic fixes skip low-confidence estimates and edition picks.
create or replace function public.set_fix_rule(p_rule text, p_auto boolean) returns void
language plpgsql security definer set search_path = public as $$
begin
  if public.my_role() is distinct from 'owner' then raise exception 'Only the owner decides what fixes itself'; end if;
  if p_rule !~ '^[a-z0-9-]{2,40}$' or p_rule like 'check%' then raise exception 'Unknown rule'; end if;
  insert into public.product_fix_rules (rule, auto, set_by, set_at) values (p_rule, p_auto, lower(auth.jwt() ->> 'email'), now())
  on conflict (rule) do update set auto = excluded.auto, set_by = excluded.set_by, set_at = excluded.set_at;
end $$;
revoke all on function public.set_fix_rule(text, boolean) from public, anon;
grant execute on function public.set_fix_rule(text, boolean) to authenticated;

-- When shopify-sync sends a change that came from a fix, the fix shows the result.
create or replace function public.product_fix_follow() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.fix_id is not null and new.status is distinct from old.status then
    update public.product_fixes set status = case new.status when 'applied' then 'applied' when 'failed' then 'failed' when 'dropped' then 'open' else status end,
      error = new.error where id = new.fix_id;
  end if;
  return new;
end $$;
drop trigger if exists product_fix_follow on public.shopify_changes;
create trigger product_fix_follow after update of status on public.shopify_changes for each row execute function public.product_fix_follow();

-- Counts for the owner's Home card and the fixer screen (manager+).
create or replace function public.product_fix_summary() returns jsonb
language sql stable security definer set search_path = public as $$
  select case when public.role_rank(public.my_role()) >= 3 then jsonb_build_object(
    'open', (select count(*) from public.product_fixes where status = 'open' and kind <> 'check'),
    'high', (select count(*) from public.product_fixes where status = 'open' and kind <> 'check' and confidence = 'high'),
    'checks', (select count(*) from public.product_fixes where status = 'open' and kind = 'check'),
    'applied_7', (select count(*) from public.product_fixes where status = 'applied' and decided_at > now() - interval '7 days'),
    'by_rule', (select coalesce(jsonb_object_agg(rule, n), '{}'::jsonb) from (select rule, count(*) n from public.product_fixes where status = 'open' group by rule) x),
    'faire_lines', (select count(*) from public.faire_order_lines),
    'faire_latest', (select max(day) from public.faire_order_lines),
    'last', (select jsonb_build_object('at', at, 'ok', ok, 'note', note) from public.shopify_sync_log where kind like 'fix%' order by id desc limit 1))
  else null end $$;
revoke all on function public.product_fix_summary() from public, anon;
grant execute on function public.product_fix_summary() to authenticated;

-- The hourly timer (20 past). Uses the same secret key as the Shopify timer.
create or replace function public.product_fix_tick() returns void
language plpgsql security definer set search_path = public as $$
declare k text; s text;
begin
  select cron_key, access_token into k, s from public.shopify_conn where id = 1;
  if s is null then return; end if;
  perform net.http_post(
    url := 'https://rtgpxuiwcdfdpnepfnoy.supabase.co/functions/v1/product-fix',
    headers := jsonb_build_object('Content-Type','application/json','x-sync-key', k),
    body := '{"action":"tick"}'::jsonb, timeout_milliseconds := 120000);
end $$;
revoke all on function public.product_fix_tick() from public, anon, authenticated;
select cron.unschedule(jobid) from cron.job where jobname = 'product-fix';
select cron.schedule('product-fix', '20 * * * *', 'select public.product_fix_tick()');
